/** Inject a tiny keyframe for the spinner — idempotent. */
export function injectSpinKeyframe() {
  if (
    typeof document === "undefined" ||
    document.getElementById("live-chat-keyframes")
  ) {
    return;
  }

  const style = document.createElement("style");
  style.id = "live-chat-keyframes";
  style.textContent = `@keyframes live-chat-spin { to { transform: rotate(360deg); } }`;
  document.head.appendChild(style);
}
